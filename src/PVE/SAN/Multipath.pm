package PVE::SAN::Multipath;

# multipath-tools integration: path states from multipathd, rendering of the
# managed conf.d snippet (aliases, path policies, detached devices) and the
# few multipath/multipathd commands pvesan issues.

use strict;
use warnings;

use File::Path ();

use PVE::SAN::Util qw(run_cmd sysfs_path list_dir read_attr);

our $CONF_FILE = '/etc/multipath/conf.d/pvesan.conf';

# vSphere path selection policies mapped onto dm-multipath settings.
our $POLICIES = {
    'array-default' => {
        description => 'Built-in multipath-tools defaults for this array model.',
        settings => [],
    },
    'round-robin' => {
        description => 'All paths active, I/O spread over all of them (like VMW_PSP_RR).',
        settings => [
            path_grouping_policy => 'multibus',
            path_selector => '"service-time 0"',
            failback => 'immediate',
        ],
    },
    'alua' => {
        description => 'Use ALUA active/optimized paths first, balance within the group (RR on ALUA arrays).',
        settings => [
            path_grouping_policy => 'group_by_prio',
            prio => 'alua',
            path_selector => '"service-time 0"',
            failback => 'immediate',
        ],
    },
    'mru' => {
        description => 'One active path; stay on the new path after a failover (like VMW_PSP_MRU).',
        settings => [
            path_grouping_policy => 'failover',
            failback => 'manual',
        ],
    },
    'fixed' => {
        description => 'One active path; fail back to the highest priority path when it returns (like VMW_PSP_FIXED).',
        settings => [
            path_grouping_policy => 'failover',
            failback => 'immediate',
        ],
    },
};

sub policy_names {
    return [ sort keys %$POLICIES ];
}

# Format string fields: dev | dm state | checker state | device state | prio | map
my $PATH_FORMAT = '%d|%t|%T|%o|%p|%m';

sub parse_paths_raw {
    my ($text) = @_;

    my $res = {};
    for my $line (split(/\n/, $text // '')) {
        my ($dev, $dm, $chk, $devst, $pri, $map) = map { s/^\s+|\s+$//gr } split(/\|/, $line, -1);
        next if !$dev || $dev !~ /^sd[a-z]+$/;
        $res->{$dev} = {
            dm_state => ($dm && $dm ne 'undef') ? $dm : undef,
            chk_state => ($chk && $chk ne 'undef') ? $chk : undef,
            dev_state => $devst,
            priority => (defined($pri) && $pri =~ /^-?\d+$/) ? int($pri) : undef,
            map => ($map && $map ne '[orphan]') ? $map : undef,
        };
    }
    return $res;
}

sub path_states {
    my $out = run_cmd(['multipathd', 'show', 'paths', 'raw', 'format', $PATH_FORMAT], noerr => 1, timeout => 15);
    return parse_paths_raw($out);
}

# Render the managed snippet from the cluster-wide device table
# ({ wwid => { alias, policy, detached } }). Output is deterministic so
# unchanged input never rewrites the file.
sub render_conf {
    my ($devices) = @_;

    my @detached = sort grep { $devices->{$_}->{detached} } keys %$devices;
    my @managed = sort grep { !$devices->{$_}->{detached} } keys %$devices;

    my $out = "# Generated by pvesan from /etc/pve/pvesan/config.json - DO NOT EDIT.\n"
        . "# Use 'pvesan device set' or the GUI (Node > Disks > SAN) instead.\n";

    if (@detached) {
        $out .= "\nblacklist {\n";
        $out .= "\twwid \"^\Q$_\E\$\"\n" for @detached;
        $out .= "}\n";
    }

    my @entries;
    for my $wwid (@managed) {
        my $d = $devices->{$wwid};
        my @lines = ("\t\twwid $wwid");
        push @lines, "\t\talias $d->{alias}" if $d->{alias};
        my $policy = $POLICIES->{$d->{policy} // 'array-default'} // $POLICIES->{'array-default'};
        my @kv = @{$policy->{settings}};
        while (my ($k, $v) = splice(@kv, 0, 2)) {
            push @lines, "\t\t$k $v";
        }
        next if @lines == 1; # nothing to override
        push @entries, "\tmultipath {\n" . join("\n", @lines) . "\n\t}\n";
    }
    $out .= "\nmultipaths {\n" . join('', @entries) . "}\n" if @entries;

    return $out;
}

# Returns 1 when the file content changed.
sub write_conf {
    my ($text) = @_;

    my $file = sysfs_path($CONF_FILE);
    my $old = '';
    if (open(my $fh, '<', $file)) {
        local $/;
        $old = <$fh> // '';
        close($fh);
    }
    return 0 if $old eq $text;

    require PVE::Tools;
    my $dir = $file =~ s|/[^/]+$||r;
    File::Path::make_path($dir) if ! -d $dir;
    PVE::Tools::file_set_contents($file, $text);
    return 1;
}

# /etc/multipath/wwids decides what find_multipaths accepts. We edit it
# directly instead of 'multipath -a', which needs the LUN to be visible -
# config is cluster-wide, but not every node sees every LUN.
our $WWIDS_FILE = '/etc/multipath/wwids';

sub read_wwids_file {
    my $file = sysfs_path($WWIDS_FILE);
    open(my $fh, '<', $file) or return '';
    local $/;
    my $c = <$fh> // '';
    close($fh);
    return $c;
}

sub write_wwids_file {
    my ($content) = @_;
    require PVE::Tools;
    my $file = sysfs_path($WWIDS_FILE);
    my $dir = $file =~ s|/[^/]+$||r;
    File::Path::make_path($dir) if ! -d $dir;
    PVE::Tools::file_set_contents($file, $content);
}

sub claimed_wwids {
    my $res = {};
    for my $line (split(/\n/, read_wwids_file())) {
        $res->{$1} = 1 if $line =~ m|^/([^/]+)/\s*$|;
    }
    return $res;
}

sub claim_wwid {
    my ($wwid) = @_;
    return if claimed_wwids()->{$wwid};
    my $c = read_wwids_file();
    $c = "# Multipath wwids, Version : 1.0\n" if !length($c);
    $c .= "\n" if $c !~ /\n$/;
    write_wwids_file($c . "/$wwid/\n");
}

sub unclaim_wwid {
    my ($wwid) = @_;
    my $c = read_wwids_file();
    my $new = join('', grep { $_ !~ m|^/\Q$wwid\E/\s*$| } split(/^/, $c));
    write_wwids_file($new) if $new ne $c;
}

sub reconfigure {
    run_cmd(['multipathd', 'reconfigure'], timeout => 60);
}

sub resize_map {
    my ($name) = @_;
    run_cmd(['multipathd', 'resize', 'map', $name], timeout => 60);
}

# Remove an unused map. Fails (by design) when anything still holds it open.
sub flush_map {
    my ($name) = @_;
    run_cmd(['multipath', '-f', $name], timeout => 60);
}

sub map_for_wwid {
    my ($wwid) = @_;

    for my $dm (list_dir('/sys/block')) {
        next if $dm !~ /^dm-\d+$/;
        my $uuid = read_attr("/sys/block/$dm/dm/uuid") // next;
        return read_attr("/sys/block/$dm/dm/name") if $uuid eq "mpath-$wwid";
    }
    return undef;
}

# Wait for udev/multipathd to create the map after a claim or reconfigure.
sub wait_for_map {
    my ($wwid, $timeout) = @_;

    $timeout //= 30;
    for (my $i = 0; $i < $timeout * 2; $i++) {
        if (my $name = map_for_wwid($wwid)) {
            return $name if -b "/dev/mapper/$name";
        }
        select(undef, undef, undef, 0.5);
    }
    return undef;
}

1;
